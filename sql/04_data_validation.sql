/* ============================================================================
   SupplyChainIQ - PHASE 1 : SYNTHETIC DATA FOUNDATION
   FILE    : 04_data_validation.sql
   PURPOSE : Prove the generated dataset is complete, referentially sound,
             realistically distributed and that the flagship scenario and its
             three intervention options are derivable from the raw records.

   READ-ONLY. This script never modifies data.

   All relative dates derive from PUBLIC.DATASET_METADATA.DATASET_ANCHOR_DATE
   (fixed constant DATE '2026-08-15'); CURRENT_DATE() is never used for
   business logic. It appears once, in V1, purely to report the session clock.

   Governed-window conventions used by validation (Phase 1 working definitions,
   NOT canonical metric definitions - those come later):
     - recent demand window      : anchor-30 .. anchor-1  (30 historical days)
     - critical customer horizon : anchor    .. anchor+14
     - latest inventory position : SNAPSHOT_DATE = DATASET_ANCHOR_DATE
   ============================================================================ */

USE ROLE ACCOUNTADMIN;
USE WAREHOUSE COMPUTE_WH;
USE DATABASE SUPPLYCHAINIQ_DB;

/* ===========================================================================
   V1 : ENVIRONMENT
   =========================================================================== */
SELECT '=== V1 ENVIRONMENT ===' AS SECTION;

SELECT
  CURRENT_ROLE()                              AS ROLE_USED,
  CURRENT_WAREHOUSE()                         AS WAREHOUSE_USED,
  CURRENT_DATABASE()                          AS DATABASE_USED,
  m.DATASET_NAME,
  m.DATASET_ANCHOR_DATE,
  m.VERSION                                   AS DATASET_VERSION,
  m.GENERATED_AT,
  CURRENT_DATE()                              AS SESSION_CURRENT_DATE,
  CURRENT_TIMESTAMP()                         AS SESSION_TIMESTAMP,
  CURRENT_ACCOUNT()                           AS ACCOUNT,
  CURRENT_VERSION()                           AS SNOWFLAKE_VERSION,
  /* the anchor is a fixed project constant, so it may differ from the session
     clock; the session timezone explains any one-day offset */
  DATEDIFF(day, CURRENT_DATE(), m.DATASET_ANCHOR_DATE) AS ANCHOR_MINUS_SESSION_DATE_DAYS
FROM PUBLIC.DATASET_METADATA m
WHERE m.VERSION = 1;

SHOW PARAMETERS LIKE 'TIMEZONE' IN ACCOUNT;

/* ===========================================================================
   V2 : SCHEMAS AND TABLES
   =========================================================================== */
SELECT '=== V2 SCHEMAS AND TABLES ===' AS SECTION;

SELECT SCHEMA_NAME, COMMENT
FROM INFORMATION_SCHEMA.SCHEMATA
WHERE CATALOG_NAME = 'SUPPLYCHAINIQ_DB'
  AND SCHEMA_NAME <> 'INFORMATION_SCHEMA'
ORDER BY SCHEMA_NAME;

SELECT TABLE_SCHEMA, TABLE_NAME, ROW_COUNT, BYTES
FROM INFORMATION_SCHEMA.TABLES
WHERE TABLE_TYPE = 'BASE TABLE'
ORDER BY TABLE_SCHEMA, TABLE_NAME;

/* CURATED must still be empty at the end of Phase 1 */
SELECT 'CURATED must be empty in Phase 1'          AS CHECK_NAME,
       0                                            AS EXPECTED_OBJECTS,
       COUNT(*)                                     AS ACTUAL_OBJECTS,
       IFF(COUNT(*) = 0, 'PASS', 'FAIL')            AS RESULT
FROM INFORMATION_SCHEMA.TABLES
WHERE TABLE_SCHEMA = 'CURATED';

/* ===========================================================================
   V3 : ROW-COUNT VALIDATION AGAINST TARGET MINIMUMS
   =========================================================================== */
SELECT '=== V3 ROW COUNTS VS TARGETS ===' AS SECTION;

WITH counts AS (
  SELECT 'SAP_ERP.VENDOR_MASTER'               AS TABLE_FQN, 'Suppliers'            AS DATASET, 100     AS MIN_TARGET, (SELECT COUNT(*) FROM SAP_ERP.VENDOR_MASTER)               AS ROW_CNT
  UNION ALL SELECT 'SAP_ERP.MATERIAL_MASTER',              'Parts',                 1000,   (SELECT COUNT(*) FROM SAP_ERP.MATERIAL_MASTER)
  UNION ALL SELECT 'SAP_ERP.PLANT_MASTER',                 'Plants',                12,     (SELECT COUNT(*) FROM SAP_ERP.PLANT_MASTER)
  UNION ALL SELECT 'SAP_ERP.SUPPLIER_MATERIAL',            'Supplier-material map', 1,      (SELECT COUNT(*) FROM SAP_ERP.SUPPLIER_MATERIAL)
  UNION ALL SELECT 'SAP_ERP.PURCHASE_ORDER_LINES',         'PO lines',              50000,  (SELECT COUNT(*) FROM SAP_ERP.PURCHASE_ORDER_LINES)
  UNION ALL SELECT 'TMS_LOGISTICS.CARRIER_MASTER',         'Carriers',              20,     (SELECT COUNT(*) FROM TMS_LOGISTICS.CARRIER_MASTER)
  UNION ALL SELECT 'TMS_LOGISTICS.SHIPMENTS',              'Shipment lines',        50000,  (SELECT COUNT(*) FROM TMS_LOGISTICS.SHIPMENTS)
  UNION ALL SELECT 'TMS_LOGISTICS.TRANSPORT_OPTIONS',      'Transport options',     1,      (SELECT COUNT(*) FROM TMS_LOGISTICS.TRANSPORT_OPTIONS)
  UNION ALL SELECT 'TMS_LOGISTICS.INTERPLANT_TRANSFER_OPTIONS','Transfer options',  1,      (SELECT COUNT(*) FROM TMS_LOGISTICS.INTERPLANT_TRANSFER_OPTIONS)
  UNION ALL SELECT 'WMS_INVENTORY.INVENTORY_SNAPSHOTS',    'Inventory snapshots',   100000, (SELECT COUNT(*) FROM WMS_INVENTORY.INVENTORY_SNAPSHOTS)
  UNION ALL SELECT 'DEMAND_PLANNING.DEMAND_HISTORY',       'Demand records',        100000, (SELECT COUNT(*) FROM DEMAND_PLANNING.DEMAND_HISTORY)
  UNION ALL SELECT 'CRM_ORDERS.CUSTOMER_MASTER',           'Customers',             500,    (SELECT COUNT(*) FROM CRM_ORDERS.CUSTOMER_MASTER)
  UNION ALL SELECT 'CRM_ORDERS.CUSTOMER_ORDER_LINES',      'Customer order lines',  50000,  (SELECT COUNT(*) FROM CRM_ORDERS.CUSTOMER_ORDER_LINES)
  UNION ALL SELECT 'SUPPLIER_PORTAL.SUPPLIER_SCORECARDS',  'Supplier scorecards',   1,      (SELECT COUNT(*) FROM SUPPLIER_PORTAL.SUPPLIER_SCORECARDS)
  UNION ALL SELECT 'SUPPLIER_PORTAL.SUPPLIER_PROFILE',     'Supplier profiles',     100,    (SELECT COUNT(*) FROM SUPPLIER_PORTAL.SUPPLIER_PROFILE)
  UNION ALL SELECT 'DOCUMENTS.SUPPLIER_DOCUMENTS',         'Documents',             100,    (SELECT COUNT(*) FROM DOCUMENTS.SUPPLIER_DOCUMENTS)
)
SELECT DATASET, TABLE_FQN, MIN_TARGET, ROW_CNT,
       IFF(ROW_CNT >= MIN_TARGET, 'PASS', 'FAIL') AS RESULT
FROM counts
ORDER BY DATASET;

SELECT 'TOTAL MAJOR SYNTHETIC RECORDS' AS METRIC,
       (SELECT COUNT(*) FROM SAP_ERP.PURCHASE_ORDER_LINES)
     + (SELECT COUNT(*) FROM TMS_LOGISTICS.SHIPMENTS)
     + (SELECT COUNT(*) FROM WMS_INVENTORY.INVENTORY_SNAPSHOTS)
     + (SELECT COUNT(*) FROM DEMAND_PLANNING.DEMAND_HISTORY)
     + (SELECT COUNT(*) FROM CRM_ORDERS.CUSTOMER_ORDER_LINES)
     + (SELECT COUNT(*) FROM SAP_ERP.VENDOR_MASTER)
     + (SELECT COUNT(*) FROM SAP_ERP.MATERIAL_MASTER)
     + (SELECT COUNT(*) FROM SAP_ERP.PLANT_MASTER)
     + (SELECT COUNT(*) FROM SAP_ERP.SUPPLIER_MATERIAL)
     + (SELECT COUNT(*) FROM CRM_ORDERS.CUSTOMER_MASTER)
     + (SELECT COUNT(*) FROM TMS_LOGISTICS.CARRIER_MASTER)
     + (SELECT COUNT(*) FROM TMS_LOGISTICS.TRANSPORT_OPTIONS)
     + (SELECT COUNT(*) FROM TMS_LOGISTICS.INTERPLANT_TRANSFER_OPTIONS)
     + (SELECT COUNT(*) FROM SUPPLIER_PORTAL.SUPPLIER_SCORECARDS)
     + (SELECT COUNT(*) FROM SUPPLIER_PORTAL.SUPPLIER_PROFILE)
     + (SELECT COUNT(*) FROM DOCUMENTS.SUPPLIER_DOCUMENTS) AS TOTAL_ROWS;

/* ===========================================================================
   V4 : DISTINCT-KEY / GRAIN VALIDATION
   =========================================================================== */
SELECT '=== V4 DISTINCT KEYS AND GRAIN ===' AS SECTION;

SELECT 'Distinct purchase orders'          AS MEASURE, COUNT(DISTINCT PO_NUMBER)::VARCHAR AS VALUE FROM SAP_ERP.PURCHASE_ORDER_LINES
UNION ALL SELECT 'PO lines',                 COUNT(*)::VARCHAR FROM SAP_ERP.PURCHASE_ORDER_LINES
UNION ALL SELECT 'Avg lines per PO',         ROUND(COUNT(*) / COUNT(DISTINCT PO_NUMBER), 2)::VARCHAR FROM SAP_ERP.PURCHASE_ORDER_LINES
UNION ALL SELECT 'Max lines per PO',         (SELECT MAX(c)::VARCHAR FROM (SELECT COUNT(*) c FROM SAP_ERP.PURCHASE_ORDER_LINES GROUP BY PO_NUMBER))
UNION ALL SELECT 'Distinct shipments',       COUNT(DISTINCT SHIPMENT_ID)::VARCHAR FROM TMS_LOGISTICS.SHIPMENTS
UNION ALL SELECT 'Shipment lines',           COUNT(*)::VARCHAR FROM TMS_LOGISTICS.SHIPMENTS
UNION ALL SELECT 'Distinct customer orders', COUNT(DISTINCT ORDER_ID)::VARCHAR FROM CRM_ORDERS.CUSTOMER_ORDER_LINES
UNION ALL SELECT 'Customer order lines',     COUNT(*)::VARCHAR FROM CRM_ORDERS.CUSTOMER_ORDER_LINES
UNION ALL SELECT 'Supplier-material rows',   COUNT(*)::VARCHAR FROM SAP_ERP.SUPPLIER_MATERIAL
UNION ALL SELECT 'Supplier scorecard rows',  COUNT(*)::VARCHAR FROM SUPPLIER_PORTAL.SUPPLIER_SCORECARDS
UNION ALL SELECT 'Transport options',        COUNT(*)::VARCHAR FROM TMS_LOGISTICS.TRANSPORT_OPTIONS
UNION ALL SELECT 'Interplant transfer options', COUNT(*)::VARCHAR FROM TMS_LOGISTICS.INTERPLANT_TRANSFER_OPTIONS
UNION ALL SELECT 'Inventory part-site combos', COUNT(DISTINCT SKU || '|' || SITE_ID)::VARCHAR FROM WMS_INVENTORY.INVENTORY_SNAPSHOTS
UNION ALL SELECT 'Inventory snapshot dates',   COUNT(DISTINCT SNAPSHOT_DATE)::VARCHAR FROM WMS_INVENTORY.INVENTORY_SNAPSHOTS
UNION ALL SELECT 'Demand part-location combos', COUNT(DISTINCT PART_ID || '|' || LOCATION_ID)::VARCHAR FROM DEMAND_PLANNING.DEMAND_HISTORY
UNION ALL SELECT 'Demand dates',               COUNT(DISTINCT DEMAND_DATE)::VARCHAR FROM DEMAND_PLANNING.DEMAND_HISTORY;

/* grain uniqueness: no duplicate business keys */
SELECT 'Duplicate PO_NUMBER+PO_LINE_NUMBER'        AS CHECK_NAME,
       COUNT(*) AS DUP_KEYS, IFF(COUNT(*) = 0, 'PASS', 'FAIL') AS RESULT
FROM (SELECT PO_NUMBER, PO_LINE_NUMBER FROM SAP_ERP.PURCHASE_ORDER_LINES
      GROUP BY 1,2 HAVING COUNT(*) > 1)
UNION ALL
SELECT 'Duplicate SHIPMENT_ID+SHIPMENT_LINE_NUMBER', COUNT(*), IFF(COUNT(*) = 0, 'PASS', 'FAIL')
FROM (SELECT SHIPMENT_ID, SHIPMENT_LINE_NUMBER FROM TMS_LOGISTICS.SHIPMENTS
      GROUP BY 1,2 HAVING COUNT(*) > 1)
UNION ALL
SELECT 'Duplicate ORDER_ID+ORDER_LINE', COUNT(*), IFF(COUNT(*) = 0, 'PASS', 'FAIL')
FROM (SELECT ORDER_ID, ORDER_LINE FROM CRM_ORDERS.CUSTOMER_ORDER_LINES
      GROUP BY 1,2 HAVING COUNT(*) > 1)
UNION ALL
SELECT 'Duplicate SITE_ID+SKU+SNAPSHOT_DATE', COUNT(*), IFF(COUNT(*) = 0, 'PASS', 'FAIL')
FROM (SELECT SITE_ID, SKU, SNAPSHOT_DATE FROM WMS_INVENTORY.INVENTORY_SNAPSHOTS
      GROUP BY 1,2,3 HAVING COUNT(*) > 1)
UNION ALL
SELECT 'Duplicate PART_ID+LOCATION_ID+DEMAND_DATE', COUNT(*), IFF(COUNT(*) = 0, 'PASS', 'FAIL')
FROM (SELECT PART_ID, LOCATION_ID, DEMAND_DATE FROM DEMAND_PLANNING.DEMAND_HISTORY
      GROUP BY 1,2,3 HAVING COUNT(*) > 1)
UNION ALL
SELECT 'Duplicate DOCUMENT_ID', COUNT(*), IFF(COUNT(*) = 0, 'PASS', 'FAIL')
FROM (SELECT DOCUMENT_ID FROM DOCUMENTS.SUPPLIER_DOCUMENTS GROUP BY 1 HAVING COUNT(*) > 1);

/* ===========================================================================
   V5 : REFERENTIAL VALIDATION - canonical business-key orphans (expect 0)
   =========================================================================== */
SELECT '=== V5 REFERENTIAL ORPHANS (EXPECT 0) ===' AS SECTION;

WITH orphans AS (
  SELECT 'shipment -> supplier (SUPPLIER_CODE -> VENDOR_ID)' AS RELATIONSHIP,
         (SELECT COUNT(*) FROM TMS_LOGISTICS.SHIPMENTS s
           WHERE s.SUPPLIER_CODE IS NOT NULL
             AND NOT EXISTS (SELECT 1 FROM SAP_ERP.VENDOR_MASTER v WHERE v.VENDOR_ID = s.SUPPLIER_CODE)) AS ORPHANS
  UNION ALL SELECT 'shipment -> part (ITEM_CODE -> MATERIAL_NO)',
         (SELECT COUNT(*) FROM TMS_LOGISTICS.SHIPMENTS s
           WHERE s.ITEM_CODE IS NOT NULL
             AND NOT EXISTS (SELECT 1 FROM SAP_ERP.MATERIAL_MASTER m WHERE m.MATERIAL_NO = s.ITEM_CODE))
  UNION ALL SELECT 'shipment -> plant (DESTINATION_SITE -> PLANT_CODE)',
         (SELECT COUNT(*) FROM TMS_LOGISTICS.SHIPMENTS s
           WHERE s.DESTINATION_SITE IS NOT NULL
             AND NOT EXISTS (SELECT 1 FROM SAP_ERP.PLANT_MASTER p WHERE p.PLANT_CODE = s.DESTINATION_SITE))
  UNION ALL SELECT 'shipment -> carrier (CARRIER_CODE)',
         (SELECT COUNT(*) FROM TMS_LOGISTICS.SHIPMENTS s
           WHERE s.CARRIER_CODE IS NOT NULL
             AND NOT EXISTS (SELECT 1 FROM TMS_LOGISTICS.CARRIER_MASTER c WHERE c.CARRIER_CODE = s.CARRIER_CODE))
  UNION ALL SELECT 'shipment -> PO (PO_REF -> PO_NUMBER)',
         (SELECT COUNT(*) FROM TMS_LOGISTICS.SHIPMENTS s
           WHERE s.PO_REF IS NOT NULL
             AND NOT EXISTS (SELECT 1 FROM SAP_ERP.PURCHASE_ORDER_LINES p WHERE p.PO_NUMBER = s.PO_REF))
  UNION ALL SELECT 'shipment -> PO line (PO_REF + PO_LINE_REF)',
         (SELECT COUNT(*) FROM TMS_LOGISTICS.SHIPMENTS s
           WHERE s.PO_REF IS NOT NULL
             AND NOT EXISTS (SELECT 1 FROM SAP_ERP.PURCHASE_ORDER_LINES p
                              WHERE p.PO_NUMBER = s.PO_REF AND p.PO_LINE_NUMBER = s.PO_LINE_REF))
  UNION ALL SELECT 'PO line -> supplier (VENDOR_ID)',
         (SELECT COUNT(*) FROM SAP_ERP.PURCHASE_ORDER_LINES p
           WHERE NOT EXISTS (SELECT 1 FROM SAP_ERP.VENDOR_MASTER v WHERE v.VENDOR_ID = p.VENDOR_ID))
  UNION ALL SELECT 'PO line -> part (MATERIAL_NO)',
         (SELECT COUNT(*) FROM SAP_ERP.PURCHASE_ORDER_LINES p
           WHERE NOT EXISTS (SELECT 1 FROM SAP_ERP.MATERIAL_MASTER m WHERE m.MATERIAL_NO = p.MATERIAL_NO))
  UNION ALL SELECT 'PO line -> plant (PLANT_CODE)',
         (SELECT COUNT(*) FROM SAP_ERP.PURCHASE_ORDER_LINES p
           WHERE NOT EXISTS (SELECT 1 FROM SAP_ERP.PLANT_MASTER pl WHERE pl.PLANT_CODE = p.PLANT_CODE))
  UNION ALL SELECT 'inventory -> part (SKU -> MATERIAL_NO)',
         (SELECT COUNT(*) FROM WMS_INVENTORY.INVENTORY_SNAPSHOTS i
           WHERE NOT EXISTS (SELECT 1 FROM SAP_ERP.MATERIAL_MASTER m WHERE m.MATERIAL_NO = i.SKU))
  UNION ALL SELECT 'inventory -> plant (SITE_ID -> PLANT_CODE)',
         (SELECT COUNT(*) FROM WMS_INVENTORY.INVENTORY_SNAPSHOTS i
           WHERE NOT EXISTS (SELECT 1 FROM SAP_ERP.PLANT_MASTER p WHERE p.PLANT_CODE = i.SITE_ID))
  UNION ALL SELECT 'customer order -> customer (CUSTOMER_ID)',
         (SELECT COUNT(*) FROM CRM_ORDERS.CUSTOMER_ORDER_LINES c
           WHERE NOT EXISTS (SELECT 1 FROM CRM_ORDERS.CUSTOMER_MASTER cm WHERE cm.CUSTOMER_ID = c.CUSTOMER_ID))
  UNION ALL SELECT 'customer order -> part (PART_NUMBER -> MATERIAL_NO)',
         (SELECT COUNT(*) FROM CRM_ORDERS.CUSTOMER_ORDER_LINES c
           WHERE NOT EXISTS (SELECT 1 FROM SAP_ERP.MATERIAL_MASTER m WHERE m.MATERIAL_NO = c.PART_NUMBER))
  UNION ALL SELECT 'customer order -> plant (FULFILLMENT_SITE -> PLANT_CODE)',
         (SELECT COUNT(*) FROM CRM_ORDERS.CUSTOMER_ORDER_LINES c
           WHERE NOT EXISTS (SELECT 1 FROM SAP_ERP.PLANT_MASTER p WHERE p.PLANT_CODE = c.FULFILLMENT_SITE))
  UNION ALL SELECT 'demand -> part (PART_ID -> MATERIAL_NO)',
         (SELECT COUNT(*) FROM DEMAND_PLANNING.DEMAND_HISTORY d
           WHERE NOT EXISTS (SELECT 1 FROM SAP_ERP.MATERIAL_MASTER m WHERE m.MATERIAL_NO = d.PART_ID))
  UNION ALL SELECT 'demand -> plant (LOCATION_ID -> PLANT_CODE)',
         (SELECT COUNT(*) FROM DEMAND_PLANNING.DEMAND_HISTORY d
           WHERE NOT EXISTS (SELECT 1 FROM SAP_ERP.PLANT_MASTER p WHERE p.PLANT_CODE = d.LOCATION_ID))
  UNION ALL SELECT 'scorecard -> supplier (SUPPLIER_ID -> VENDOR_ID)',
         (SELECT COUNT(*) FROM SUPPLIER_PORTAL.SUPPLIER_SCORECARDS s
           WHERE NOT EXISTS (SELECT 1 FROM SAP_ERP.VENDOR_MASTER v WHERE v.VENDOR_ID = s.SUPPLIER_ID))
  UNION ALL SELECT 'portal profile -> supplier (SUPPLIER_ID -> VENDOR_ID)',
         (SELECT COUNT(*) FROM SUPPLIER_PORTAL.SUPPLIER_PROFILE s
           WHERE NOT EXISTS (SELECT 1 FROM SAP_ERP.VENDOR_MASTER v WHERE v.VENDOR_ID = s.SUPPLIER_ID))
  UNION ALL SELECT 'supplier-material -> supplier (VENDOR_ID)',
         (SELECT COUNT(*) FROM SAP_ERP.SUPPLIER_MATERIAL sm
           WHERE NOT EXISTS (SELECT 1 FROM SAP_ERP.VENDOR_MASTER v WHERE v.VENDOR_ID = sm.VENDOR_ID))
  UNION ALL SELECT 'supplier-material -> part (MATERIAL_NO)',
         (SELECT COUNT(*) FROM SAP_ERP.SUPPLIER_MATERIAL sm
           WHERE NOT EXISTS (SELECT 1 FROM SAP_ERP.MATERIAL_MASTER m WHERE m.MATERIAL_NO = sm.MATERIAL_NO))
  UNION ALL SELECT 'document -> supplier (supplier-specific docs only)',
         (SELECT COUNT(*) FROM DOCUMENTS.SUPPLIER_DOCUMENTS d
           WHERE d.SUPPLIER_ID IS NOT NULL
             AND NOT EXISTS (SELECT 1 FROM SAP_ERP.VENDOR_MASTER v WHERE v.VENDOR_ID = d.SUPPLIER_ID))
  UNION ALL SELECT 'transport option -> plant (DESTINATION_PLANT)',
         (SELECT COUNT(*) FROM TMS_LOGISTICS.TRANSPORT_OPTIONS t
           WHERE NOT EXISTS (SELECT 1 FROM SAP_ERP.PLANT_MASTER p WHERE p.PLANT_CODE = t.DESTINATION_PLANT))
  UNION ALL SELECT 'transfer option -> plants (ORIGIN/DESTINATION_PLANT)',
         (SELECT COUNT(*) FROM TMS_LOGISTICS.INTERPLANT_TRANSFER_OPTIONS t
           WHERE NOT EXISTS (SELECT 1 FROM SAP_ERP.PLANT_MASTER p WHERE p.PLANT_CODE = t.ORIGIN_PLANT)
              OR NOT EXISTS (SELECT 1 FROM SAP_ERP.PLANT_MASTER p WHERE p.PLANT_CODE = t.DESTINATION_PLANT))
)
SELECT RELATIONSHIP, ORPHANS, IFF(ORPHANS = 0, 'PASS', 'FAIL') AS RESULT
FROM orphans
ORDER BY ORPHANS DESC, RELATIONSHIP;

SELECT 'TOTAL CANONICAL BUSINESS-KEY ORPHANS' AS CHECK_NAME,
       (SELECT COUNT(*) FROM TMS_LOGISTICS.SHIPMENTS s
         WHERE NOT EXISTS (SELECT 1 FROM SAP_ERP.PURCHASE_ORDER_LINES p
                            WHERE p.PO_NUMBER = s.PO_REF AND p.PO_LINE_NUMBER = s.PO_LINE_REF))
     + (SELECT COUNT(*) FROM SAP_ERP.PURCHASE_ORDER_LINES p
         WHERE NOT EXISTS (SELECT 1 FROM SAP_ERP.VENDOR_MASTER v WHERE v.VENDOR_ID = p.VENDOR_ID))
     + (SELECT COUNT(*) FROM WMS_INVENTORY.INVENTORY_SNAPSHOTS i
         WHERE NOT EXISTS (SELECT 1 FROM SAP_ERP.MATERIAL_MASTER m WHERE m.MATERIAL_NO = i.SKU))
     + (SELECT COUNT(*) FROM CRM_ORDERS.CUSTOMER_ORDER_LINES c
         WHERE NOT EXISTS (SELECT 1 FROM CRM_ORDERS.CUSTOMER_MASTER cm WHERE cm.CUSTOMER_ID = c.CUSTOMER_ID))
     + (SELECT COUNT(*) FROM DEMAND_PLANNING.DEMAND_HISTORY d
         WHERE NOT EXISTS (SELECT 1 FROM SAP_ERP.MATERIAL_MASTER m WHERE m.MATERIAL_NO = d.PART_ID))
       AS TOTAL_ORPHANS;

/* inventory / demand coverage alignment (needed for future DOI) */
SELECT 'Inventory part-site combos WITHOUT demand history' AS CHECK_NAME,
       COUNT(*) AS COMBOS,
       IFF(COUNT(*) = 0, 'PASS', 'REVIEW') AS RESULT
FROM (SELECT DISTINCT SKU, SITE_ID FROM WMS_INVENTORY.INVENTORY_SNAPSHOTS) i
WHERE NOT EXISTS (SELECT 1 FROM DEMAND_PLANNING.DEMAND_HISTORY d
                   WHERE d.PART_ID = i.SKU AND d.LOCATION_ID = i.SITE_ID);

/* ===========================================================================
   V6 : DISTRIBUTION VALIDATION
   =========================================================================== */
SELECT '=== V6 DISTRIBUTIONS ===' AS SECTION;

/* shipment timing mix */
WITH s AS (
  SELECT SHIPMENT_STATUS,
         ACTUAL_DELIVERY_DATE, EXPECTED_DELIVERY_DATE,
         SHIPPED_QTY, RECEIVED_QTY
  FROM TMS_LOGISTICS.SHIPMENTS
), t AS (
  SELECT COUNT(*) AS total,
         COUNT_IF(ACTUAL_DELIVERY_DATE IS NULL)                                   AS open_lines,
         COUNT_IF(ACTUAL_DELIVERY_DATE <  EXPECTED_DELIVERY_DATE)                 AS early_lines,
         COUNT_IF(ACTUAL_DELIVERY_DATE =  EXPECTED_DELIVERY_DATE)                 AS ontime_lines,
         COUNT_IF(ACTUAL_DELIVERY_DATE >  EXPECTED_DELIVERY_DATE)                 AS late_lines,
         COUNT_IF(RECEIVED_QTY > 0 AND RECEIVED_QTY < SHIPPED_QTY)                AS partial_lines,
         COUNT_IF(SHIPMENT_STATUS = 'IN_TRANSIT')                                 AS in_transit_lines
  FROM s
)
SELECT 'Shipment lines'            AS MEASURE, total::VARCHAR AS VALUE, NULL AS PCT FROM t
UNION ALL SELECT 'Early',        early_lines::VARCHAR,      ROUND(100.0 * early_lines / total, 2) FROM t
UNION ALL SELECT 'On time',      ontime_lines::VARCHAR,     ROUND(100.0 * ontime_lines / total, 2) FROM t
UNION ALL SELECT 'Late',         late_lines::VARCHAR,       ROUND(100.0 * late_lines / total, 2) FROM t
UNION ALL SELECT 'Not delivered (open)', open_lines::VARCHAR, ROUND(100.0 * open_lines / total, 2) FROM t
UNION ALL SELECT 'In transit',   in_transit_lines::VARCHAR, ROUND(100.0 * in_transit_lines / total, 2) FROM t
UNION ALL SELECT 'Partial (qty)', partial_lines::VARCHAR,   ROUND(100.0 * partial_lines / total, 2) FROM t;

SELECT SHIPMENT_STATUS, COUNT(*) AS LINES,
       ROUND(100.0 * COUNT(*) / SUM(COUNT(*)) OVER (), 2) AS PCT
FROM TMS_LOGISTICS.SHIPMENTS GROUP BY 1 ORDER BY LINES DESC;

SELECT TRANSPORT_MODE, COUNT(*) AS LINES,
       ROUND(100.0 * COUNT(*) / SUM(COUNT(*)) OVER (), 2) AS PCT
FROM TMS_LOGISTICS.SHIPMENTS GROUP BY 1 ORDER BY LINES DESC;

/* PO status mix - cancelled share must be ~3-5% */
SELECT PO_STATUS, COUNT(*) AS LINES,
       ROUND(100.0 * COUNT(*) / SUM(COUNT(*)) OVER (), 2) AS PCT
FROM SAP_ERP.PURCHASE_ORDER_LINES GROUP BY 1 ORDER BY LINES DESC;

SELECT 'Cancelled PO line share' AS CHECK_NAME,
       '3% - 5%' AS EXPECTED,
       ROUND(100.0 * COUNT_IF(PO_STATUS = 'CANCELLED') / COUNT(*), 2) AS ACTUAL_PCT,
       IFF(100.0 * COUNT_IF(PO_STATUS = 'CANCELLED') / COUNT(*) BETWEEN 3 AND 5, 'PASS', 'REVIEW') AS RESULT
FROM SAP_ERP.PURCHASE_ORDER_LINES;

/* customer order mix */
SELECT ORDER_STATUS, COUNT(*) AS LINES,
       ROUND(100.0 * COUNT(*) / SUM(COUNT(*)) OVER (), 2) AS PCT,
       SUM(ORDER_VALUE) AS ORDER_VALUE_INR
FROM CRM_ORDERS.CUSTOMER_ORDER_LINES GROUP BY 1 ORDER BY LINES DESC;

SELECT 'Partially fulfilled customer order lines' AS MEASURE,
       COUNT_IF(FULFILLED_QTY > 0 AND FULFILLED_QTY < ORDERED_QTY) AS LINES,
       ROUND(100.0 * COUNT_IF(FULFILLED_QTY > 0 AND FULFILLED_QTY < ORDERED_QTY) / COUNT(*), 2) AS PCT
FROM CRM_ORDERS.CUSTOMER_ORDER_LINES;

SELECT PRIORITY, COUNT(*) AS LINES,
       ROUND(100.0 * COUNT(*) / SUM(COUNT(*)) OVER (), 2) AS PCT
FROM CRM_ORDERS.CUSTOMER_ORDER_LINES GROUP BY 1 ORDER BY LINES DESC;

/* master-data distributions */
SELECT 'Supplier tier' AS DIMENSION, VENDOR_TIER AS VALUE, COUNT(*) AS N FROM SAP_ERP.VENDOR_MASTER GROUP BY 1,2
UNION ALL SELECT 'Supplier status', VENDOR_STATUS, COUNT(*) FROM SAP_ERP.VENDOR_MASTER GROUP BY 1,2
UNION ALL SELECT 'Supplier region', REGION, COUNT(*) FROM SAP_ERP.VENDOR_MASTER GROUP BY 1,2
UNION ALL SELECT 'Part criticality', CRITICALITY, COUNT(*) FROM SAP_ERP.MATERIAL_MASTER GROUP BY 1,2
UNION ALL SELECT 'Product family', PRODUCT_FAMILY, COUNT(*) FROM SAP_ERP.MATERIAL_MASTER GROUP BY 1,2
UNION ALL SELECT 'Plant region', REGION, COUNT(*) FROM SAP_ERP.PLANT_MASTER GROUP BY 1,2
UNION ALL SELECT 'Customer segment', CUSTOMER_SEGMENT, COUNT(*) FROM CRM_ORDERS.CUSTOMER_MASTER GROUP BY 1,2
UNION ALL SELECT 'Customer priority tier', PRIORITY_TIER, COUNT(*) FROM CRM_ORDERS.CUSTOMER_MASTER GROUP BY 1,2
UNION ALL SELECT 'Carrier mode', TRANSPORT_MODE, COUNT(*) FROM TMS_LOGISTICS.CARRIER_MASTER GROUP BY 1,2
UNION ALL SELECT 'Document type', DOCUMENT_TYPE, COUNT(*) FROM DOCUMENTS.SUPPLIER_DOCUMENTS GROUP BY 1,2
ORDER BY DIMENSION, N DESC;

/* latest-snapshot inventory status mix */
SELECT i.INVENTORY_STATUS, COUNT(*) AS POSITIONS,
       ROUND(100.0 * COUNT(*) / SUM(COUNT(*)) OVER (), 2) AS PCT
FROM WMS_INVENTORY.INVENTORY_SNAPSHOTS i
JOIN PUBLIC.DATASET_METADATA m ON m.VERSION = 1 AND i.SNAPSHOT_DATE = m.DATASET_ANCHOR_DATE
GROUP BY 1 ORDER BY POSITIONS DESC;

/* supplier risk mix on the latest scorecard per supplier */
SELECT RISK_CATEGORY, COUNT(*) AS SUPPLIERS,
       ROUND(100.0 * COUNT(*) / SUM(COUNT(*)) OVER (), 2) AS PCT
FROM (SELECT SUPPLIER_ID, RISK_CATEGORY
      FROM SUPPLIER_PORTAL.SUPPLIER_SCORECARDS
      QUALIFY ROW_NUMBER() OVER (PARTITION BY SUPPLIER_ID ORDER BY SCORECARD_DATE DESC) = 1)
