/* ===========================================================================
   CHECK 1 : Exactly 14 expected CURATED views exist, no unexpected objects
   =========================================================================== */
WITH expected AS (
  SELECT * FROM (VALUES
    ('SUPPLIER'),('PART'),('PLANT'),('SUPPLIER_PART'),('PURCHASE_ORDER_LINE'),
    ('SHIPMENT'),('INVENTORY_SNAPSHOT'),('DEMAND'),('CUSTOMER'),
    ('CUSTOMER_ORDER_LINE'),('CARRIER'),('SUPPLIER_PERFORMANCE'),
    ('TRANSPORT_OPTION'),('INTERPLANT_TRANSFER_OPTION')
  ) AS t(VIEW_NAME)
),
actual AS (
  SELECT TABLE_NAME AS VIEW_NAME FROM INFORMATION_SCHEMA.VIEWS WHERE TABLE_SCHEMA = 'CURATED'
)
SELECT '1. Exactly 14 expected CURATED views, no extras/missing' AS CHECK_NAME,
       IFF(
         (SELECT COUNT(*) FROM actual) = 14
         AND (SELECT COUNT(*) FROM expected e WHERE NOT EXISTS (SELECT 1 FROM actual a WHERE a.VIEW_NAME = e.VIEW_NAME)) = 0
         AND (SELECT COUNT(*) FROM actual a WHERE NOT EXISTS (SELECT 1 FROM expected e WHERE e.VIEW_NAME = a.VIEW_NAME)) = 0,
         'PASS','FAIL') AS RESULT;

