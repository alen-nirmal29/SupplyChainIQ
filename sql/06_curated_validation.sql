/* ===========================================================================
   CHECK 11 : Flagship scenario S017 -> P104 -> P01 reproduced via CURATED
   =========================================================================== */
WITH a AS (SELECT DATASET_ANCHOR_DATE AS A FROM PUBLIC.DATASET_METADATA WHERE VERSION = 1),
f AS (
  SELECT
    (SELECT i.AVAILABLE_QTY FROM CURATED.INVENTORY_SNAPSHOT i CROSS JOIN a
      WHERE i.PART_ID='P104' AND i.PLANT_ID='P01' AND i.SNAPSHOT_DATE=a.A)                AS avail,
    (SELECT i.SAFETY_STOCK_QTY FROM CURATED.INVENTORY_SNAPSHOT i CROSS JOIN a
      WHERE i.PART_ID='P104' AND i.PLANT_ID='P01' AND i.SNAPSHOT_DATE=a.A)                AS ss,
    (SELECT COUNT(*) FROM CURATED.CUSTOMER_ORDER_LINE c CROSS JOIN a
      WHERE c.PART_ID='P104' AND c.PLANT_ID='P01' AND c.ORDER_STATUS='OPEN'
        AND c.DUE_DATE BETWEEN a.A AND DATEADD(day,14,a.A))                               AS n_orders,
    (SELECT SUM(c.ORDERED_QTY) FROM CURATED.CUSTOMER_ORDER_LINE c CROSS JOIN a
      WHERE c.PART_ID='P104' AND c.PLANT_ID='P01' AND c.ORDER_STATUS='OPEN'
        AND c.DUE_DATE BETWEEN a.A AND DATEADD(day,14,a.A))                               AS req,
    (SELECT SUM(c.ORDER_VALUE) FROM CURATED.CUSTOMER_ORDER_LINE c CROSS JOIN a
      WHERE c.PART_ID='P104' AND c.PLANT_ID='P01' AND c.ORDER_STATUS='OPEN'
        AND c.DUE_DATE BETWEEN a.A AND DATEADD(day,14,a.A))                               AS exposure,
    (SELECT ROUND(AVG(d.ACTUAL_DEMAND_QTY),2) FROM CURATED.DEMAND d CROSS JOIN a
      WHERE d.PART_ID='P104' AND d.PLANT_ID='P01'
        AND d.DEMAND_DATE BETWEEN DATEADD(day,-30,a.A) AND DATEADD(day,-1,a.A))           AS add30,
    (SELECT MAX(DATEDIFF(day, s.EXPECTED_DELIVERY_DATE, s.PROJECTED_DELIVERY_DATE))
       FROM CURATED.SHIPMENT s
      WHERE s.SUPPLIER_ID='S017' AND s.PART_ID='P104' AND s.PLANT_ID='P01'
        AND s.ACTUAL_DELIVERY_DATE IS NULL)                                               AS delay
)
SELECT '11a. AVAILABLE_QTY = 8200' AS ASSERTION, IFF(avail = 8200, 'PASS','FAIL') AS RESULT FROM f
UNION ALL SELECT '11b. SAFETY_STOCK_QTY = 3000',       IFF(ss = 3000, 'PASS','FAIL') FROM f
UNION ALL SELECT '11c. SAFE_USABLE_INVENTORY = 5200',  IFF(avail - ss = 5200, 'PASS','FAIL') FROM f
UNION ALL SELECT '11d. AFFECTED_CUSTOMER_ORDERS = 3',  IFF(n_orders = 3, 'PASS','FAIL') FROM f
UNION ALL SELECT '11e. CUSTOMER_REQUIREMENT = 7350',   IFF(req = 7350, 'PASS','FAIL') FROM f
UNION ALL SELECT '11f. PROJECTED_SHORTAGE = 2150',     IFF(req - (avail - ss) = 2150, 'PASS','FAIL') FROM f
UNION ALL SELECT '11g. REVENUE_EXPOSURE_INR = 4200000',IFF(exposure = 4200000, 'PASS','FAIL') FROM f
UNION ALL SELECT '11h. AVG_DAILY_DEMAND_30D ~700',      IFF(add30 BETWEEN 660 AND 740, 'PASS','FAIL') FROM f
UNION ALL SELECT '11i. SHIPMENT_DELAY_DAYS = 5',        IFF(delay = 5, 'PASS','FAIL') FROM f
UNION ALL
SELECT '11j. Expedite APAC->P01 option available (faster+costlier)',
       IFF(EXISTS (SELECT 1 FROM CURATED.TRANSPORT_OPTION t
                   JOIN CURATED.SUPPLIER v ON v.SUPPLIER_ID='S017' AND v.REGION=t.ORIGIN_REGION
                   WHERE t.DESTINATION_PLANT_ID='P01' AND t.ACTIVE_FLAG
                     AND t.EXPEDITED_TRANSIT_DAYS < t.NORMAL_TRANSIT_DAYS
                     AND t.EXPEDITE_COST_FACTOR > t.NORMAL_COST_FACTOR
                     AND t.EXPEDITED_TRANSIT_DAYS < 12), 'PASS','FAIL')
UNION ALL
SELECT '11k. P03->P01 transfer option capacity >= 2150',
       IFF((SELECT LEAST(i.AVAILABLE_QTY - i.SAFETY_STOCK_QTY, o.MAX_TRANSFER_QTY)
              FROM CURATED.INVENTORY_SNAPSHOT i, CURATED.INTERPLANT_TRANSFER_OPTION o, PUBLIC.DATASET_METADATA md
             WHERE i.PART_ID='P104' AND i.PLANT_ID='P03' AND i.SNAPSHOT_DATE=md.DATASET_ANCHOR_DATE AND md.VERSION=1
               AND o.ORIGIN_PLANT_ID='P03' AND o.DESTINATION_PLANT_ID='P01' AND o.ACTIVE_FLAG) >= 2150,
       'PASS','FAIL')
UNION ALL
SELECT '11l. S042 approved for P104, capacity >=2150, lead time <=7d, active',
       IFF(EXISTS (SELECT 1 FROM CURATED.SUPPLIER_PART sp
                   JOIN CURATED.SUPPLIER v ON v.SUPPLIER_ID = sp.SUPPLIER_ID
                   WHERE sp.SUPPLIER_ID='S042' AND sp.PART_ID='P104'
                     AND sp.MAX_WEEKLY_SUPPLY_QTY >= 2150
                     AND sp.CONTRACT_LEAD_TIME_DAYS <= 7
                     AND v.VENDOR_STATUS = 'Active'), 'PASS','FAIL')
UNION ALL
SELECT '11m. S042 priced above S017 for P104',
       IFF((SELECT AGREED_UNIT_PRICE FROM CURATED.SUPPLIER_PART WHERE SUPPLIER_ID='S042' AND PART_ID='P104')
         > (SELECT AGREED_UNIT_PRICE FROM CURATED.SUPPLIER_PART WHERE SUPPLIER_ID='S017' AND PART_ID='P104'),
       'PASS','FAIL');

