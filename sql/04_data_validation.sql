/* deterioration trend for S055 (first vs latest scorecard) */
SELECT SUPPLIER_ID,
       MIN_BY(QUALITY_SCORE, SCORECARD_DATE)  AS OLDEST_QUALITY,
       MAX_BY(QUALITY_SCORE, SCORECARD_DATE)  AS LATEST_QUALITY,
       MIN_BY(SERVICE_SCORE, SCORECARD_DATE)  AS OLDEST_SERVICE,
       MAX_BY(SERVICE_SCORE, SCORECARD_DATE)  AS LATEST_SERVICE,
       MIN_BY(REJECTION_RATE, SCORECARD_DATE) AS OLDEST_REJECTION,
       MAX_BY(REJECTION_RATE, SCORECARD_DATE) AS LATEST_REJECTION,
       /* materiality threshold: ignore small month-to-month scorecard noise */
       ROUND(MAX_BY(SERVICE_SCORE, SCORECARD_DATE) - MIN_BY(SERVICE_SCORE, SCORECARD_DATE), 2) AS SERVICE_DELTA,
       CASE WHEN MAX_BY(SERVICE_SCORE, SCORECARD_DATE) - MIN_BY(SERVICE_SCORE, SCORECARD_DATE) <= -10
              THEN 'DETERIORATING'
            WHEN MAX_BY(SERVICE_SCORE, SCORECARD_DATE) - MIN_BY(SERVICE_SCORE, SCORECARD_DATE) >= 10
              THEN 'IMPROVING'
            ELSE 'STABLE' END AS TREND
FROM SUPPLIER_PORTAL.SUPPLIER_SCORECARDS
WHERE SUPPLIER_ID IN ('S055','S011','S017','S042')
GROUP BY SUPPLIER_ID ORDER BY SUPPLIER_ID;

