SELECT 'A1. Exactly 15 AI_VERIFIED_QUERY objects registered' AS CHECK_NAME,
       IFF((SELECT COUNT(DISTINCT "object_name") FROM TABLE(RESULT_SCAN(LAST_QUERY_ID())) WHERE "object_kind" = 'AI_VERIFIED_QUERY') = 15, 'PASS', 'FAIL') AS RESULT
UNION ALL
SELECT 'A2. Names are exactly VQ01-VQ11, VQ12_V2, VQ13-VQ15, no duplicates, no extras',
       IFF(
         (SELECT ARRAY_SORT(ARRAY_AGG(DISTINCT "object_name")) FROM TABLE(RESULT_SCAN(LAST_QUERY_ID())) WHERE "object_kind" = 'AI_VERIFIED_QUERY')
           = ARRAY_SORT(ARRAY_CONSTRUCT('VQ01','VQ02','VQ03','VQ04','VQ05','VQ06','VQ07','VQ08','VQ09','VQ10','VQ11','VQ12_V2','VQ13','VQ14','VQ15')),
       'PASS', 'FAIL')
UNION ALL
SELECT 'A3. QUESTION populated for every VQ',
       IFF((SELECT COUNT(DISTINCT "object_name") FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()))
             WHERE "object_kind" = 'AI_VERIFIED_QUERY' AND "property" = 'QUESTION' AND LENGTH("property_value") > 0) = 15,
       'PASS', 'FAIL')
UNION ALL
SELECT 'A4. SQL populated for every VQ',
       IFF((SELECT COUNT(DISTINCT "object_name") FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()))
             WHERE "object_kind" = 'AI_VERIFIED_QUERY' AND "property" = 'SQL' AND LENGTH("property_value") > 0) = 15,
       'PASS', 'FAIL')
UNION ALL
SELECT 'A5. VERIFIED_AT populated for every VQ',
       IFF((SELECT COUNT(DISTINCT "object_name") FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()))
             WHERE "object_kind" = 'AI_VERIFIED_QUERY' AND "property" = 'VERIFIED_AT' AND "property_value" IS NOT NULL) = 15,
       'PASS', 'FAIL')
UNION ALL
SELECT 'A6. VERIFIED_BY populated for every VQ',
       IFF((SELECT COUNT(DISTINCT "object_name") FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()))
             WHERE "object_kind" = 'AI_VERIFIED_QUERY' AND "property" = 'VERIFIED_BY' AND LENGTH("property_value") > 0) = 15,
       'PASS', 'FAIL')
UNION ALL
SELECT 'A7. ONBOARDING_QUESTION = TRUE for exactly VQ01, VQ04, VQ05, VQ06, VQ09',
       IFF(
         (SELECT ARRAY_SORT(ARRAY_AGG("object_name")) FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()))
           WHERE "object_kind" = 'AI_VERIFIED_QUERY' AND "property" = 'ONBOARDING_QUESTION' AND "property_value" = 'TRUE')
           = ARRAY_SORT(ARRAY_CONSTRUCT('VQ01','VQ04','VQ05','VQ06','VQ09')),
       'PASS', 'FAIL')
UNION ALL
SELECT 'A8. No AI_VERIFIED_QUERY SQL contains a CURATED.* physical table reference',
       IFF((SELECT COUNT(*) FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()))
             WHERE "object_kind" = 'AI_VERIFIED_QUERY' AND "property" = 'SQL' AND UPPER("property_value") LIKE '%CURATED.%') = 0,
       'PASS', 'FAIL')
UNION ALL
SELECT 'A9. No AI_VERIFIED_QUERY SQL contains a semicolon (single-statement rule)',
       IFF((SELECT COUNT(*) FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()))
             WHERE "object_kind" = 'AI_VERIFIED_QUERY' AND "property" = 'SQL' AND "property_value" LIKE '%;%') = 0,
       'PASS', 'FAIL')
UNION ALL
SELECT 'A10. Existing tables/relationships/dimensions/facts/metrics still present (12/15/54/26/32)',
       IFF(
            (SELECT COUNT(DISTINCT "object_name") FROM TABLE(RESULT_SCAN(LAST_QUERY_ID())) WHERE "object_kind" = 'TABLE') = 12
        AND (SELECT COUNT(DISTINCT "object_name") FROM TABLE(RESULT_SCAN(LAST_QUERY_ID())) WHERE "object_kind" = 'RELATIONSHIP') = 15
        AND (SELECT COUNT(*) FROM TABLE(RESULT_SCAN(LAST_QUERY_ID())) WHERE "object_kind" = 'DIMENSION' AND "property" = 'TABLE') = 54
        AND (SELECT COUNT(*) FROM TABLE(RESULT_SCAN(LAST_QUERY_ID())) WHERE "object_kind" = 'FACT' AND "property" = 'TABLE') = 26
        AND (SELECT COUNT(*) FROM TABLE(RESULT_SCAN(LAST_QUERY_ID())) WHERE "object_kind" = 'METRIC' AND "property" = 'TABLE') = 32,
       'PASS', 'FAIL');

