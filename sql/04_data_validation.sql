/* plant with high inventory cover but weak demand (latest snapshot vs 30-day demand) */
WITH a AS (SELECT DATASET_ANCHOR_DATE AS A FROM PUBLIC.DATASET_METADATA WHERE VERSION = 1),
d AS (
  SELECT LOCATION_ID, SUM(ACTUAL_DEMAND_QTY) / 30.0 AS AVG_DAILY_DEMAND
  FROM DEMAND_PLANNING.DEMAND_HISTORY, a
  WHERE DEMAND_DATE BETWEEN DATEADD(day,-30,a.A) AND DATEADD(day,-1,a.A)
  GROUP BY 1
),
i AS (
  SELECT SITE_ID, SUM(AVAILABLE_QTY) AS AVAILABLE_QTY
  FROM WMS_INVENTORY.INVENTORY_SNAPSHOTS, a
  WHERE SNAPSHOT_DATE = a.A GROUP BY 1
)
SELECT i.SITE_ID AS PLANT, i.AVAILABLE_QTY, ROUND(d.AVG_DAILY_DEMAND, 2) AS AVG_DAILY_DEMAND,
       ROUND(i.AVAILABLE_QTY / NULLIF(d.AVG_DAILY_DEMAND, 0), 1) AS DAYS_OF_COVER
FROM i JOIN d ON d.LOCATION_ID = i.SITE_ID
ORDER BY DAYS_OF_COVER DESC;

